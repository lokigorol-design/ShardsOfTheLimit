def set_text(paragraph, text: str) -> None:
    for run in list(paragraph.runs):
        run._element.getparent().remove(run._element)
    paragraph.add_run(text)


def paragraph_index(doc: Document, exact_text: str) -> int:
    for index, paragraph in enumerate(doc.paragraphs):
        if paragraph.text.strip() == exact_text:
            return index
    raise ValueError(f"Paragraph not found: {exact_text}")


def set_startswith(doc: Document, prefix: str, text: str) -> None:
    for paragraph in doc.paragraphs:
        if paragraph.text.strip().startswith(prefix):
            set_text(paragraph, text)
            return
    raise ValueError(f"Paragraph prefix not found: {prefix}")


def insert_after(paragraph, text: str, style: str | None = None):
    new_paragraph = paragraph._parent.add_paragraph(style=style or paragraph.style)
    paragraph._p.addnext(new_paragraph._p)
    new_paragraph.add_run(text)
    return new_paragraph


def replace_block(
    doc: Document,
    start_text: str,
    end_text: str,
    rows: list[tuple[str, str]],
) -> None:
    start = paragraph_index(doc, start_text)
    end = paragraph_index(doc, end_text)
    if end <= start:
        raise ValueError(f"Invalid block: {start_text} -> {end_text}")

    anchor = doc.paragraphs[start]
    for paragraph in list(doc.paragraphs[start + 1 : end]):
        paragraph._element.getparent().remove(paragraph._element)

    for style, text in reversed(rows):
        insert_after(anchor, text, style)


